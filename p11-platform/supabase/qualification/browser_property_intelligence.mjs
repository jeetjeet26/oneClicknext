/** Local synthetic fixture only; real UI, API and database calls. */
import {createRequire} from 'node:module'
import {readFile} from 'node:fs/promises'
import path from 'node:path'
const web=path.resolve(import.meta.dirname,'../../apps/web')
const require=createRequire(path.join(web,'package.json'))
const {chromium,expect}=require('@playwright/test')
const {createServerClient}=require('@supabase/ssr')
const config=JSON.parse(await readFile(process.argv[2],'utf8'))
if(!['127.0.0.1','localhost'].includes(new URL(config.webUrl).hostname))throw Error('Local qualification only')
const A='bc000000-0000-4000-8000-000000000001',B='bc000000-0000-4000-8000-000000000002'
const cookies=[],auth=createServerClient(config.gateway,config.anon,{cookies:{getAll:()=>[],setAll:items=>cookies.push(...items)}})
const {error}=await auth.auth.setSession(config.session)
if(error)throw Error('Synthetic session unavailable')
const browser=await chromium.launch({headless:true})
let count=0
function check(value,label){if(!value)throw Error(label);count++;console.log(JSON.stringify({state:'passed',check:label}))}
try{
  const context=await browser.newContext({viewport:{width:1365,height:1000}})
  await context.route('**/*',route=>{const u=new URL(route.request().url());return ['127.0.0.1','localhost'].includes(u.hostname)||['data:','blob:'].includes(u.protocol)?route.continue():route.abort()})
  await context.addCookies(cookies.map(c=>({name:c.name,value:c.value,url:config.webUrl})))
  await context.addInitScript(id=>{if(!localStorage.getItem('p11_selected_property_id'))localStorage.setItem('p11_selected_property_id',id)},A)
  const page=await context.newPage(),errors=[]
  process.on('uncaughtException',async error=>{console.error((await page.locator('body').innerText()).slice(-8000));await page.screenshot({path:'/private/tmp/property-intelligence-failed.png',fullPage:true});console.error(error);await browser.close();process.exit(1)})
  page.setDefaultTimeout(45000)
  page.on('pageerror',e=>errors.push(e.message))
  const go=route=>page.goto(config.webUrl+route,{waitUntil:'domcontentloaded',timeout:180000})
  const reportFor=id=>page.waitForResponse(r=>{const u=new URL(r.url());return u.pathname==='/api/intelligence'&&u.searchParams.get('kind')==='portfolio'&&u.searchParams.get('propertyId')===id})
  const firstReport=reportFor(A)
  await go('/dashboard/intelligence')
  const first=await firstReport
  if(!first.ok())throw Error('Property report failed: '+await first.text())
  check((await first.json()).properties.every(p=>p.score.id===A),'Default Intelligence report contains only selected community A')
  await expect(page.getByRole('heading',{name:'Community A performance',exact:true})).toBeVisible()
  check(await page.getByRole('button',{name:'Property record',exact:true}).count()===0,'Intelligence has no competing fact editor')
  check(await page.getByRole('button',{name:'Creative direction',exact:true}).count()===0,'Intelligence has no creative-direction editor')
  await page.screenshot({path:'/private/tmp/property-intelligence-desktop.png',fullPage:true})
  const nextReport=reportFor(B)
  await page.getByRole('combobox',{name:'Property',exact:true}).selectOption(B)
  const next=await nextReport
  check(next.ok()&&(await next.json()).properties.every(p=>p.score.id===B),'Property switch reloads the report with only community B')
  await expect(page.getByRole('heading',{name:'Community B performance',exact:true})).toBeVisible()
  await expect(page.getByRole('heading',{name:'Community A performance',exact:true})).toHaveCount(0)
  const questionResponse=page.waitForResponse(r=>r.url().endsWith('/api/intelligence')&&r.request().method()==='POST')
  await page.getByLabel('Question about property results').fill('What sources are missing?')
  await page.getByRole('button',{name:'Ask',exact:true}).click()
  const question=await questionResponse
  check(question.ok()&&question.request().postDataJSON().propertyId===B,'Questions carry the same selected-property scope')
  const unscoped=await context.request.get(config.webUrl+'/api/intelligence?kind=portfolio&start=2026-10-01&end=2026-10-10')
  check(unscoped.status()===400,'API rejects an omitted property instead of expanding to the portfolio')
  await page.getByRole('combobox',{name:'Property',exact:true}).selectOption(A)
  await go('/dashboard/community?section=facts')
  await expect(page.getByRole('heading',{name:'Approved community facts',exact:true})).toBeVisible()
  await page.getByRole('combobox',{name:/^Property field/}).selectOption('market')
  await page.getByLabel('Approved information',{exact:true}).fill('Intelligence boundary fixture market')
  await page.getByLabel('Who or what supplied this?',{exact:true}).fill('Synthetic local review')
  const saveResponse=page.waitForResponse(r=>r.url().endsWith('/api/intelligence')&&r.request().method()==='POST')
  await page.getByRole('button',{name:'Save draft',exact:true}).click()
  const saved=await saveResponse
  if(!saved.ok())throw Error('Fact save failed: '+await saved.text())
  check(saved.request().postDataJSON().propertyId===A,'Knowledge editor uses the global selection after navigation')
  const article=page.locator('article').filter({hasText:'Intelligence boundary fixture market'})
  await expect(article).toBeVisible()
  const approval=page.waitForResponse(r=>r.url().endsWith('/api/intelligence')&&r.request().method()==='POST')
  await article.getByRole('button',{name:'Approve',exact:true}).click()
  check((await approval).ok(),'Moved fact editor retains the real approval workflow')
  await page.getByRole('combobox',{name:'Property',exact:true}).selectOption(B)
  await expect(page.getByRole('heading',{name:'Approved community facts',exact:true})).toBeVisible()
  await expect(page.getByText('Intelligence boundary fixture market',{exact:true})).toHaveCount(0)
  check(true,'Approved community A information is absent from community B’s editor')
  await go('/dashboard/bi')
  await expect(page).toHaveURL(/\/dashboard\/intelligence\?section=campaigns/)
  await expect(page.getByRole('heading',{name:'Campaign performance',exact:true})).toBeVisible()
  check(true,'Existing BI links open campaign detail within Intelligence')
  await go('/dashboard/community-brain')
  await expect(page).toHaveURL(/\/dashboard\/community\?section=files/)
  await expect(page.getByRole('heading',{name:'Community files and assets',exact:true})).toBeVisible()
  check(await page.getByRole('combobox',{name:'Community',exact:true}).count()===0,'Community files use the global property instead of a second selection')
  await page.getByRole('combobox',{name:'Property',exact:true}).selectOption(A)
  await go('/dashboard/portfolio')
  await expect(page.getByRole('heading',{name:'Portfolio assistant',exact:true})).toBeVisible()
  await expect(page.getByRole('button',{name:'Ask the portfolio assistant',exact:true})).toBeDisabled()
  await page.getByRole('checkbox',{name:'Community A',exact:true}).check()
  await page.getByRole('combobox',{name:'Find or compare',exact:true}).selectOption('facts')
  const portfolioResponse=page.waitForResponse(r=>r.url().endsWith('/api/community-brain/portfolio')&&r.request().method()==='POST')
  await page.getByRole('button',{name:'Ask the portfolio assistant',exact:true}).click()
  const portfolio=await portfolioResponse
  if(!portfolio.ok())throw Error('Portfolio failed: '+await portfolio.text())
  const data=await portfolio.json()
  check(data.propertyIds.length===1&&data.propertyIds[0]===A,'Portfolio assistant uses only explicitly checked communities')
  check(JSON.stringify(data.groups).includes('Intelligence boundary fixture market'),'Community Brain consumes the fact approved in Community knowledge')
  await go('/dashboard/siteforge/direction')
  await expect(page.getByRole('heading',{name:'Property design brief',exact:true})).toBeVisible()
  check(await page.getByLabel('Creative concept',{exact:true}).count()===1,'Reusable design brief is available only in SiteForge’s direction screen')
  await page.setViewportSize({width:390,height:844})
  await go('/dashboard/intelligence')
  await expect(page.getByRole('heading',{name:'Community A performance',exact:true})).toBeVisible()
  await page.screenshot({path:'/private/tmp/property-intelligence-mobile.png',fullPage:true})
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1),'Intelligence stays within the mobile viewport')
  check(errors.length===0,'No browser runtime errors in the tested flows')
  console.log(JSON.stringify({state:'passed',checks:count,liveEndpointsContacted:false}))
}finally{await browser.close()}
